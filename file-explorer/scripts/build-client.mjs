// Builds client/dist/index.js, the prebuilt client that index.client.tsx re-exports.
//
// Paseo's plugin compiler (packages/server/src/server/plugins/compiler.ts) bundles the client
// with esbuild at target es2020 and leaves class syntax in place. Metro never lets class syntax
// reach Hermes in app code, and Hermes on iOS and Android fails to load the bundled
// CodeMirror/Lezer classes ("Cannot read property 'prototype' of undefined"). So this script
// bundles client/entry.tsx the way the host does, then lowers the output with the Babel
// transforms @react-native/babel-preset applies for Hermes. The host compiler then bundles this
// file like any other source, and finds no class syntax to leave in.
//
// Run with `npm run build:client` after changing anything the client imports. Output is
// deterministic, and CI fails when the committed file is stale.

import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { transformSync, traverse } from "@babel/core";
import { build } from "esbuild";

const require = createRequire(import.meta.url);
const PLUGIN_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = "client/entry.tsx";
const OUT_DIR = path.join(PLUGIN_DIR, "client", "dist");

// Supplied by the app at runtime. Same list as the host compiler's client target.
const HOST_MODULES = [
  "@getpaseo/plugin",
  "@getpaseo/plugin/server",
  "@getpaseo/plugin/server/provider",
  "@getpaseo/plugin/server/usage",
  "@getpaseo/plugin/server/acp",
  "@getpaseo/plugin/client",
  "@getpaseo/plugin/client/ui",
  "@getpaseo/plugin/client/react-native",
  "@tanstack/react-query",
  "react",
  "react/jsx-runtime",
  "react-native",
  "zod",
];

// The ones @react-native/babel-preset (0.81) runs for Hermes that change syntax esbuild leaves at
// es2020. Options match the preset: `loose` on the class-feature transforms, defaults elsewhere.
const HERMES_TRANSFORMS = [
  ["@babel/plugin-transform-class-properties", { loose: true }],
  ["@babel/plugin-transform-private-methods", { loose: true }],
  ["@babel/plugin-transform-private-property-in-object", { loose: true }],
  ["@babel/plugin-transform-classes", {}],
  ["@babel/plugin-transform-block-scoping", {}],
];

const JS_HEADER = `// GENERATED by scripts/build-client.mjs from ${ENTRY}. Do not edit; run \`npm run build:client\`.
// Prebuilt so class syntax is lowered before Hermes sees it: Paseo's plugin compiler keeps it,
// and Hermes on iOS and Android fails on it. See scripts/build-client.mjs.
`;

const DTS = `// GENERATED by scripts/build-client.mjs. Types client/dist/index.js, built from ${ENTRY}.
import type { PluginClientContribution } from "@getpaseo/plugin/client";

declare const contribute: PluginClientContribution;
export default contribute;
`;

async function bundle() {
  const result = await build({
    // Relative working directory keeps absolute paths out of esbuild's `// path` comments.
    absWorkingDir: PLUGIN_DIR,
    entryPoints: [ENTRY],
    bundle: true,
    // ESM, not the host's CJS: host modules stay `import` statements for the host to resolve.
    format: "esm",
    jsx: "automatic",
    platform: "neutral",
    target: "es2020",
    mainFields: ["module", "main"],
    supported: { "async-await": false },
    external: HOST_MODULES,
    treeShaking: true,
    logLevel: "warning",
    write: false,
  });
  const output = result.outputFiles[0]?.text;
  if (!output) throw new Error(`esbuild produced no output for ${ENTRY}`);
  return output;
}

function lower(code) {
  const result = transformSync(code, {
    ast: true,
    babelrc: false,
    configFile: false,
    cwd: PLUGIN_DIR,
    filename: "client/dist/index.js",
    sourceType: "module",
    compact: false,
    plugins: HERMES_TRANSFORMS.map(([name, options]) => [require.resolve(name), options]),
  });
  if (!result?.code || !result.ast) throw new Error("Babel produced no output");
  assertLowered(result.ast);
  if (result.code.includes(PLUGIN_DIR)) throw new Error("Output contains an absolute path");
  return result.code;
}

// Checks the syntax tree, since grammar keyword strings like "class interface" fool a regex.
function assertLowered(ast) {
  traverse(ast, {
    "Class|PrivateName"(nodePath) {
      const line = nodePath.node.loc?.start.line ?? "?";
      throw new Error(`${nodePath.node.type} survived lowering (output line ${line})`);
    },
  });
}

const code = lower(await bundle());
await mkdir(OUT_DIR, { recursive: true });
await writeFile(path.join(OUT_DIR, "index.js"), `${JS_HEADER}${code}\n`);
await writeFile(path.join(OUT_DIR, "index.d.ts"), DTS);
console.log(`Wrote client/dist/index.js (${Buffer.byteLength(code)} bytes) and index.d.ts`);
