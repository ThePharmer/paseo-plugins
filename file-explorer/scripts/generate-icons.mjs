// Rasterizes the file-type icons into client/file-icons.generated.ts.
//
// Plugin client bundles are built by esbuild with no asset loaders, and plugins cannot import
// react-native-svg, so the icons ship as PNG data URIs inside a TypeScript module. react-native
// Image renders those on iOS, Android, and web.
//
// Run with `npm run generate:icons` after changing anything under scripts/icon-source/.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { EXTENSION_TO_ICON, SVG_ICONS } from "./icon-source/material-file-icons.mjs";
import { toneSvg } from "./icon-source/tone.mjs";

/** Pixel size of every PNG. 3x a 16pt row icon, so it stays sharp on high-density screens. */
const ICON_PX = 48;
const DEFAULT_ICON = "_default";
const OUTPUT = fileURLToPath(new URL("../client/file-icons.generated.ts", import.meta.url));

function withPixelSize(svg, name) {
  const root = svg.match(/^<svg\b[^>]*>/);
  if (!root) throw new Error(`Icon ${name} does not start with an <svg> element`);
  if (/\s(width|height)=/.test(root[0])) {
    throw new Error(`Icon ${name} already sets width or height; teach the generator to replace it`);
  }
  return svg.replace(/^<svg\b/, `<svg width="${ICON_PX}" height="${ICON_PX}"`);
}

async function rasterize(name, svg) {
  const png = await sharp(Buffer.from(withPixelSize(toneSvg(svg), name)))
    .resize(ICON_PX, ICON_PX, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ palette: true, compressionLevel: 9, effort: 10 })
    .toBuffer();
  return `data:image/png;base64,${png.toString("base64")}`;
}

function objectKey(key) {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

function objectLiteral(entries) {
  return entries.map(([key, value]) => `  ${objectKey(key)}: ${JSON.stringify(value)},`).join("\n");
}

async function main() {
  if (!SVG_ICONS[DEFAULT_ICON]) throw new Error(`SVG_ICONS is missing ${DEFAULT_ICON}`);

  const extensions = Object.entries(EXTENSION_TO_ICON).sort(([a], [b]) => a.localeCompare(b));
  for (const [ext, icon] of extensions) {
    if (!SVG_ICONS[icon]) throw new Error(`Extension ${ext} maps to missing icon ${icon}`);
  }

  // Only icons something can resolve to. Unreferenced vendor SVGs would be dead weight.
  const used = new Set([DEFAULT_ICON, ...extensions.map(([, icon]) => icon)]);
  const names = [...used].sort((a, b) => a.localeCompare(b));
  const uris = [];
  for (const name of names) {
    uris.push([name, await rasterize(name, SVG_ICONS[name])]);
  }

  const source = `// GENERATED by scripts/generate-icons.mjs. Do not edit by hand.
// Regenerate with \`npm run generate:icons\` (sources live in scripts/icon-source/).
//
// Icons from material-icon-theme 5.32.0, MIT License, Copyright (c) 2025 Material Extensions.
// Colour-toned as in Paseo (Apache-2.0). See THIRD_PARTY_NOTICES.md.

export const DEFAULT_FILE_ICON = ${JSON.stringify(DEFAULT_ICON)};

/** Icon name to a ${ICON_PX}x${ICON_PX} palette PNG data URI. */
export const FILE_ICON_URIS: Readonly<Record<string, string>> = {
${objectLiteral(uris)}
};

/** Lowercase file extension, without the dot, to icon name. */
export const EXTENSION_TO_ICON: Readonly<Record<string, string>> = {
${objectLiteral(extensions)}
};
`;

  await writeFile(OUTPUT, source);
  const bytes = Buffer.byteLength(source);
  console.log(
    `Wrote ${names.length} icons and ${extensions.length} extensions to client/file-icons.generated.ts (${(bytes / 1024).toFixed(1)} KiB)`,
  );
}

await main();
